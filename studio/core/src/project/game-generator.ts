/** `space-kid-journey` → `SpaceKidJourney` (a valid C# assembly / namespace identifier). */
export function assemblyName(id: string): string {
  const s = id
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0]!.toUpperCase() + p.slice(1))
    .join('');
  return /^[A-Za-z]/.test(s) ? s : `Game${s}`;
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

// Godot physical keycodes (Key enum) for the names the spec uses.
const SPECIAL: Record<string, number> = {
  up: 4194320,
  down: 4194322,
  left: 4194319,
  right: 4194321,
  space: 32,
  escape: 4194305,
  esc: 4194305,
  enter: 4194309,
  return: 4194309,
  tab: 4194306,
  shift: 4194325,
  ctrl: 4194326,
  control: 4194326,
  alt: 4194328,
  backspace: 4194308,
};

export function physicalKeycode(name: string): number | null {
  const k = name.trim().toLowerCase();
  if (k in SPECIAL) return SPECIAL[k]!;
  if (/^[a-z]$/.test(k)) return k.toUpperCase().charCodeAt(0);
  if (/^[0-9]$/.test(k)) return k.charCodeAt(0);
  if (/^f([1-9]|1[0-2])$/.test(k)) return 4194332 + Number(k.slice(1)) - 1;
  return null;
}

const keyEvent = (code: number) =>
  `Object(InputEventKey,"resource_local_to_scene":false,"resource_name":"","device":-1,"window_id":0,"alt_pressed":false,"shift_pressed":false,"ctrl_pressed":false,"meta_pressed":false,"pressed":false,"keycode":0,"physical_keycode":${code},"key_label":0,"unicode":0,"location":0,"echo":false,"script":null)`;

/** Actions the generated gameplay needs even if the spec omits them. */
const REQUIRED_ACTIONS: Record<string, string[]> = {
  move_forward: ['W', 'Up'],
  move_back: ['S', 'Down'],
  move_left: ['A', 'Left'],
  move_right: ['D', 'Right'],
  jump: ['Space'],
  interact: ['E'],
  pause: ['Escape'],
};

function inputMap(spec: GameSpec): string {
  const actions = new Map<string, string[]>();
  for (const [a, keys] of Object.entries(REQUIRED_ACTIONS)) actions.set(a, keys);
  for (const c of spec.controls) if (c.default_keys.length) actions.set(c.action, c.default_keys);
  const out: string[] = [];
  for (const [action, keys] of [...actions.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const codes = [...new Set(keys.map(physicalKeycode).filter((c): c is number => c !== null))];
    out.push(`${action}={\n"deadzone": 0.2,\n"events": [${codes.map(keyEvent).join(', ')}]\n}`);
  }
  return out.join('\n');
}

