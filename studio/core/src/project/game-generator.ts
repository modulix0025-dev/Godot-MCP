const GAME_STATE = (spec: GameSpec, levels: string[], shop: string | null, menu: string | null) => `extends Node
## Global game state (autoload "GameState"). Generated by ModuleX Game Studio from the Game Specification.

signal score_changed(score: int)
signal lives_changed(lives: int)
signal message(text: String)

const LEVELS: Array[String] = [${levels.map((l) => `"${l}"`).join(', ')}]
const LEVEL_NAMES: Array[String] = [${spec.levels.map((l) => `"${esc(l.name)}"`).join(', ')}]
const LEVEL_GOALS: Array[String] = [${spec.levels.map((l) => `"${esc(l.goal)}"`).join(', ')}]
const SHOP_SCENE := "${shop ?? ''}"
const MENU_SCENE := "${menu ?? ''}"
const WIN_SCENE := "res://scenes/win.tscn"
const SAVE_ENABLED := ${spec.save_system.required ? 'true' : 'false'}
const SAVE_PATH := "user://save.json"
const START_LIVES := 3

var score := 0
var lives := START_LIVES
var level_index := 0
var unlocked := 1
var cosmetics: Dictionary = {}


func _ready() -> void:
	load_game()


func start_game() -> void:
	score = 0
	lives = START_LIVES
	level_index = 0
	_go_level()


func continue_game() -> void:
	level_index = clampi(unlocked - 1, 0, LEVELS.size() - 1)
	lives = START_LIVES
	_go_level()


func level_name() -> String:
	return LEVEL_NAMES[level_index] if level_index < LEVEL_NAMES.size() else ""


func level_goal() -> String:
	return LEVEL_GOALS[level_index] if level_index < LEVEL_GOALS.size() else ""


func add_score(points: int) -> void:
	score += points
	score_changed.emit(score)


func hit() -> void:
	lives -= 1
	lives_changed.emit(lives)
	if lives <= 0:
		lose()


func level_complete() -> void:
	level_index += 1
	unlocked = maxi(unlocked, level_index + 1)
	save_game()
	if level_index >= LEVELS.size():
		get_tree().call_deferred("change_scene_to_file", WIN_SCENE)
	elif SHOP_SCENE != "":
		get_tree().call_deferred("change_scene_to_file", SHOP_SCENE)
	else:
		_go_level()


func continue_from_shop() -> void:
	_go_level()


func lose() -> void:
	message.emit("Try again!")
	lives = START_LIVES
	_go_level()


func back_to_menu() -> void:
	if MENU_SCENE != "":
		get_tree().call_deferred("change_scene_to_file", MENU_SCENE)
	else:
		start_game()


func buy(item: String, cost: int) -> bool:
	if score < cost or cosmetics.has(item):
		return false
	score -= cost
	cosmetics[item] = true
	score_changed.emit(score)
	save_game()
	return true


func _go_level() -> void:
	get_tree().paused = false
	get_tree().call_deferred("change_scene_to_file", LEVELS[level_index])


func save_game() -> void:
	if not SAVE_ENABLED:
		return
	var f := FileAccess.open(SAVE_PATH, FileAccess.WRITE)
	if f:
		f.store_string(JSON.stringify({"score": score, "unlocked": unlocked, "cosmetics": cosmetics}))


func load_game() -> void:
	if not SAVE_ENABLED or not FileAccess.file_exists(SAVE_PATH):
		return
	var f := FileAccess.open(SAVE_PATH, FileAccess.READ)
	if f == null:
		return
	var data = JSON.parse_string(f.get_as_text())
	if data is Dictionary:
		score = int(data.get("score", 0))
		unlocked = int(data.get("unlocked", 1))
		cosmetics = data.get("cosmetics", {})
`;

const PLAYER = `extends CharacterBody3D
## Third-person player controller. Moves with move_forward/back/left/right, jumps with jump.

const SPEED := 6.0
const JUMP_VELOCITY := 5.5
const KILL_PLANE := -12.0

var gravity: float = ProjectSettings.get_setting("physics/3d/default_gravity")
var _knockback := Vector3.ZERO


func _ready() -> void:
	add_to_group("player")
	if GameState.cosmetics.has("suit_gold"):
		_tint(Color(1.0, 0.8, 0.2))
	elif GameState.cosmetics.has("suit_blue"):
		_tint(Color(0.3, 0.5, 1.0))


func _tint(c: Color) -> void:
	var mesh := get_node_or_null("Mesh") as MeshInstance3D
	if mesh:
		var m := StandardMaterial3D.new()
		m.albedo_color = c
		mesh.material_override = m


func _physics_process(delta: float) -> void:
	if not is_on_floor():
		velocity.y -= gravity * delta
	if Input.is_action_just_pressed("jump") and is_on_floor():
		velocity.y = JUMP_VELOCITY
	var input := Input.get_vector("move_left", "move_right", "move_forward", "move_back")
	var dir := Vector3(input.x, 0.0, input.y)
	if dir.length() > 0.01:
		dir = dir.normalized()
		velocity.x = dir.x * SPEED
		velocity.z = dir.z * SPEED
		look_at(global_position + Vector3(dir.x, 0.0, dir.z), Vector3.UP)
	else:
		velocity.x = move_toward(velocity.x, 0.0, SPEED)
		velocity.z = move_toward(velocity.z, 0.0, SPEED)
	velocity += _knockback
	_knockback = _knockback.move_toward(Vector3.ZERO, 20.0 * delta)
	move_and_slide()
	if global_position.y < KILL_PLANE:
		GameState.lose()


func knockback(from: Vector3) -> void:
	var away := (global_position - from)
	away.y = 0.0
	_knockback = away.normalized() * 8.0 + Vector3.UP * 3.0
`;

