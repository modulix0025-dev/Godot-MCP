export function generateProject(
  spec: GameSpec,
  projectGuid = '8F2C4E10-5B7A-4D3E-9A61-2C0D1E7F4A90',
): GeneratedProject {
  const assembly = assemblyName(spec.project.id);
  const sceneIds = new Set(spec.scenes.map((s) => s.id));
  const menuId = [...sceneIds].find((s) => /menu|title|start/i.test(s)) ?? null;
  const shopId = [...sceneIds].find((s) => /shop|store/i.test(s)) ?? null;
  const levelScenes = spec.levels.map((l) => `res://scenes/${l.scene}.tscn`);
  const menu = menuId ? `res://scenes/${menuId}.tscn` : null;
  const shop = shopId ? `res://scenes/${shopId}.tscn` : null;
  const mainScene = menu ?? levelScenes[0]!;
  const hazardous = spec.mechanics.some((m) =>
    /hazard|enemy|meteor|obstacle|trap|damage|خطر|عدو/i.test(`${m.id} ${m.description}`),
  );

  const files: GeneratedFile[] = [
    { path: 'project.godot', content: projectGodot(spec, assembly, mainScene) },
    { path: `${assembly}.csproj`, content: csproj(assembly) },
    { path: `${assembly}.sln`, content: solution(assembly, projectGuid) },
    { path: 'export_presets.cfg', content: exportPresets(spec, assembly) },
    { path: 'scripts/game_state.gd', content: GAME_STATE(spec, levelScenes, shop, menu) },
    { path: 'scripts/player.gd', content: PLAYER },
    { path: 'scripts/collectible.gd', content: COLLECTIBLE },
    { path: 'scripts/hazard.gd', content: HAZARD },
    { path: 'scripts/exit.gd', content: EXIT },
    { path: 'scripts/level.gd', content: LEVEL },
    { path: 'scripts/hud.gd', content: HUD },
    { path: 'scripts/win.gd', content: WIN },
    { path: 'scenes/player.tscn', content: PLAYER_TSCN },
    { path: 'scenes/collectible.tscn', content: COLLECTIBLE_TSCN },
    { path: 'scenes/hazard.tscn', content: HAZARD_TSCN },
    { path: 'scenes/exit.tscn', content: EXIT_TSCN },
    { path: 'scenes/hud.tscn', content: HUD_TSCN },
    {
      path: 'scenes/win.tscn',
      content: uiScene(
        'Win',
        'win.gd',
        spec.win_conditions[0] ?? 'You win!',
        `${scoreLabel}\n${button('Again', 'Play again')}`,
      ),
    },
  ];
  spec.levels.forEach((l, i) => {
    files.push({
      path: `scenes/${l.scene}.tscn`,
      content: levelTscn(i, 5 + i * 2, hazardous ? 1 + Math.min(i, 3) : 0),
    });
  });
  if (menuId) {
    files.push({ path: 'scripts/main_menu.gd', content: MENU });
    files.push({
      path: `scenes/${menuId}.tscn`,
      content: uiScene(
        'MainMenu',
        'main_menu.gd',
        spec.project.name,
        `${button('Start', 'Start')}\n${button('Continue', 'Continue')}\n${button('Quit', 'Quit')}`,
      ),
    });
  }
  if (shopId) {
    files.push({ path: 'scripts/shop.gd', content: SHOP });
    files.push({
      path: `scenes/${shopId}.tscn`,
      content: uiScene(
        'Shop',
        'shop.gd',
        'Shop',
        `${scoreLabel}\n${button('Blue', 'Blue suit — 5')}\n${button('Gold', 'Gold suit — 15')}\n${button('Continue', 'Continue')}`,
      ),
    });
  }
  // Scenes the spec lists that the template does not specialise get an honest placeholder screen.
  for (const s of spec.scenes) {
    if (spec.levels.some((l) => l.scene === s.id) || s.id === menuId || s.id === shopId) continue;
    files.push({
      path: `scenes/${s.id}.tscn`,
      content: uiScene(assemblyName(s.id), 'win.gd', s.purpose, `${scoreLabel}\n${button('Again', 'Back')}`),
    });
  }
  const proceduralAssets: Record<string, string> = {};
  for (const a of spec.assets) {
    proceduralAssets[a.id] =
      a.type === 'character'
        ? 'res://scenes/player.tscn'
        : a.type === 'environment'
          ? levelScenes[0]!
          : /hazard|meteor|enemy|obstacle/i.test(`${a.id} ${a.description}`)
            ? 'res://scenes/hazard.tscn'
            : /exit|rocket|portal|door|goal/i.test(`${a.id} ${a.description}`)
              ? 'res://scenes/exit.tscn'
              : 'res://scenes/collectible.tscn';
  }
  return { assembly, slug: assembly.toLowerCase(), mainScene, levelScenes, files, proceduralAssets };
}
