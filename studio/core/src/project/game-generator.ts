// Game generator (Phases 6 + 10): compiles a validated GAME_SPEC into a complete, playable Godot 4.5.1 (.NET)
// project — the `game-3d-basic` template instantiated for this spec. Deterministic: the same spec always yields
// the same files, so a resumed run can compare instead of redo.
//
// What it produces (all plain text Godot resources; Godot re-saves them on import):
//   project.godot       name, main scene, input map from spec.controls (+ required defaults), GameState and
//                       ModulexQa autoloads, both editor plugins, file logging for debug builds
//   <Assembly>.csproj   Godot.NET.Sdk/4.5.1, the pinned NuGet refs, the catalog EmbeddedResource, and the
//                       ExportRelease exclusion of both addons (build-profiles.md)
//   export_presets.cfg  "Windows Desktop", "Android" (arm64, APK), "iOS" (team id empty → PREPARED only)
//   scripts/*.gd        game_state (score, lives, levels, save), player, collectible, hazard, exit, level,
//                       hud (pause), main_menu, shop, win
//   scenes/*.tscn       one scene per spec level (ground, light, player, collectibles, hazards, exit, HUD),
//                       plus main menu / shop when the spec lists them, and a win screen
//
// Assets are PROCEDURAL primitives (capsule player, glowing collectibles, hazard spheres, exit pad). They are
